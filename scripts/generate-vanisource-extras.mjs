// Regenerates src/constants/vanisourceExtras.ts — the catalog of Srila
// Prabhupada's non-book works (lectures, letters, conversations) hosted on
// vanisource.org.
//
// Only page TITLES are stored. The text itself is fetched at runtime from
// vanisource, exactly as the books are — nothing is vendored into the repo.
//
// Run:  node scripts/generate-vanisource-extras.mjs
//
// vanisource's MediaWiki search API is broken server-side (DBQueryError), so
// pages are enumerated with list=allpages by title prefix, which works.
import { writeFileSync } from 'node:fs';

const API = 'https://vanisource.org/w/api.php';
const UA =
  'Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/124.0.0.0 Safari/537.36';

async function allPages(prefix) {
  const out = [];
  let cont = null;
  do {
    const u = new URL(API);
    u.searchParams.set('action', 'query');
    u.searchParams.set('list', 'allpages');
    u.searchParams.set('apprefix', prefix);
    u.searchParams.set('aplimit', '500');
    u.searchParams.set('apnamespace', '0');
    u.searchParams.set('format', 'json');
    u.searchParams.set('formatversion', '2');
    if (cont) u.searchParams.set('apcontinue', cont);
    const res = await fetch(u, { headers: { 'User-Agent': UA } });
    if (!res.ok) throw new Error(`${prefix}: HTTP ${res.status}`);
    const json = await res.json();
    for (const p of json?.query?.allpages ?? []) out.push(p.title);
    cont = json?.continue?.apcontinue ?? null;
  } while (cont);
  return out;
}

// Every title ends with its date, e.g. "-- New York, March 4, 1966" or
// "-- Bombay 26 July, 1974". Take the last plausible 4-digit year.
function yearOf(title) {
  const years = [...title.matchAll(/\b(19[3-9]\d)\b/g)].map((m) => Number(m[1]));
  return years.length ? years[years.length - 1] : null;
}

// "Lecture on BG 2.11 -- New York, March 4, 1966" -> 'bg'
function lectureGroup(title) {
  const m = /^Lecture on ([A-Za-z-]+)/.exec(title);
  const code = (m?.[1] ?? '').toUpperCase();
  if (code === 'BG') return 'lec-bg';
  if (code === 'SB') return 'lec-sb';
  if (code === 'CC') return 'lec-cc';
  if (code === 'SI' || code === 'ISO') return 'lec-iso';
  if (code === 'NOD' || code === 'NOI') return 'lec-nod';
  return 'lec-gen';
}

// Strip the redundant leading noun so list rows read as the occasion + date.
function displayTitle(title) {
  return title.replace(/^(Lecture on |Lecture, |Lecture |Letter to:?\s*)/, '').trim() || title;
}

const GROUPS = {
  lecture: {
    prefixes: ['Lecture'],
    assign: lectureGroup,
  },
  initiation: { prefixes: ['Initiation'], assign: () => 'lec-init' },
  purport: { prefixes: ['Purport to'], assign: () => 'lec-purport' },
  letter: { prefixes: ['Letter to'], assign: (t) => `let-${yearOf(t) ?? 'undated'}` },
  conversation: {
    prefixes: ['Morning Walk', 'Room Conversation', 'Conversation', 'Interview',
               'Press', 'Radio', 'Evening', 'Arrival', 'Departure'],
    assign: (t) => `conv-${yearOf(t) ?? 'undated'}`,
  },
};

const LABELS = {
  'lec-bg': 'Bhagavad-gītā Lectures',
  'lec-sb': 'Śrīmad-Bhāgavatam Lectures',
  'lec-cc': 'Caitanya-caritāmṛta Lectures',
  'lec-iso': 'Śrī Īśopaniṣad Lectures',
  'lec-nod': 'Nectar of Devotion Lectures',
  'lec-gen': 'General & Festival Lectures',
  'lec-init': 'Initiation Lectures',
  'lec-purport': 'Song Purports',
};

const CATEGORY_OF = (slug) =>
  slug.startsWith('let-') ? 'letter' : slug.startsWith('conv-') ? 'conversation' : 'lecture';

const run = async () => {
  const buckets = new Map(); // slug -> [pageTitle]
  for (const [name, spec] of Object.entries(GROUPS)) {
    for (const prefix of spec.prefixes) {
      const pages = await allPages(prefix);
      process.stderr.write(`${name}/${prefix}: ${pages.length}\n`);
      for (const p of pages) {
        const slug = spec.assign(p);
        if (!buckets.has(slug)) buckets.set(slug, []);
        buckets.get(slug).push(p);
      }
    }
  }

  // Deterministic output: sort slugs, and pages within each slug.
  const slugs = [...buckets.keys()].sort();
  const meta = {};
  const entries = {};
  let total = 0;
  for (const slug of slugs) {
    const pages = [...new Set(buckets.get(slug))].sort((a, b) => a.localeCompare(b));
    total += pages.length;
    entries[slug] = pages;
    const year = slug.split('-')[1];
    meta[slug] = {
      title: LABELS[slug] ?? (slug.startsWith('let-') ? `Letters — ${year}` : `Conversations — ${year}`),
      category: CATEGORY_OF(slug),
      count: pages.length,
    };
  }

  const body = `// AUTO-GENERATED by scripts/generate-vanisource-extras.mjs — do not hand-edit.
//
// Catalog of Srila Prabhupada's lectures, letters and conversations on
// vanisource.org. Only page titles are stored here; the content itself is
// fetched from vanisource at runtime, the same way the books are.
//
// Generated: ${new Date().toISOString().slice(0, 10)} — ${total} pages.

export interface ExtraMeta {
  title: string;
  category: 'lecture' | 'letter' | 'conversation';
  count: number;
}

export const EXTRAS_META: Record<string, ExtraMeta> = ${JSON.stringify(meta, null, 2)};

// slug -> MediaWiki page titles (used directly as the page id when fetching).
export const EXTRAS_PAGES: Record<string, string[]> = {
${slugs.map((s) => `  ${JSON.stringify(s)}: ${JSON.stringify(entries[s])},`).join('\n')}
};

// Display name for a row — the leading noun is redundant next to the section.
export function extraDisplayTitle(pageTitle: string): string {
  return pageTitle.replace(/^(Lecture on |Lecture, |Lecture |Letter to:?\\s*)/, '').trim() || pageTitle;
}
`;

  writeFileSync(new URL('../src/constants/vanisourceExtras.ts', import.meta.url), body);
  process.stderr.write(`\nWrote ${slugs.length} sections, ${total} pages.\n`);
};

run().catch((e) => {
  process.stderr.write(`FAILED: ${e.message}\n`);
  process.exit(1);
});
